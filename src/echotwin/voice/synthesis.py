"""Voice synthesis orchestration: consent + backend + profile + provenance.

Text generation and audio generation are independent: this module only speaks
audio. Provenance metadata is written next to every output so generated audio can
be traced and disclosed as AI-generated when shared.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from pydantic import BaseModel, Field

from ..exceptions import BackendNotAvailableError
from ..settings import get_settings
from ..voice.consent import require_voice_consent
from ..voice.metadata import VoiceProfile, load_profile
from ..voice.registry import get_backend


class SynthesisResult(BaseModel):
    output_path: str
    backend: str
    backend_version: str
    model_id: str
    reference_recording_ids: list[str] = Field(default_factory=list)
    language: str = "auto"
    transcript_mode: bool = False
    settings: dict = Field(default_factory=dict)
    seed: int | None = None
    created_at: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())
    provenance: dict = Field(default_factory=dict)


def _selected_ids(profile: VoiceProfile) -> list[str]:
    sel = profile.reference_selection or {}
    return [r.get("recording_id", "") for r in sel.get("selected", []) if r.get("recording_id")]


def synthesize(
    *,
    profile_id: str,
    text: str,
    language: str = "auto",
    seed: int | None = None,
    backend_name: str | None = None,
    settings: dict | None = None,
    output_path: str | Path | None = None,
) -> SynthesisResult:
    require_voice_consent()
    profile = load_profile(profile_id)
    backend_name = backend_name or profile.backend
    settings = settings or {}

    ids = _selected_ids(profile)
    if not ids:
        raise BackendNotAvailableError(
            "This profile has no reference-audio selection yet. Run "
            "'echotwin voice recommend' and select references first."
        )
    # Bilingual profiles: prefer the reference recorded in the requested
    # language (Hindi vs English timbre/prosody transfer better that way).
    # Falls back to the top-ranked clip when unavailable.
    chosen_id = ids[0]
    lang_key = language.lower().split("-")[0] if language and language != "auto" else ""
    if lang_key in {"hi", "en"}:
        per_lang = (profile.reference_selection or {}).get("per_language", {})
        preferred = per_lang.get(lang_key)
        if preferred and preferred in ids:
            chosen_id = preferred
    rec = next((r for r in profile.recordings if r.recording_id == chosen_id), None)
    if rec is None or not Path(rec.path).exists():
        raise BackendNotAvailableError(
            f"Reference recording '{chosen_id}' is missing on disk; reselect references."
        )

    backend = get_backend(backend_name)
    caps = backend.capabilities()

    out_dir = get_settings().artifacts_dir / "audio"
    out_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now(UTC).strftime("%Y%m%dT%H%M%S")
    out = Path(output_path) if output_path else out_dir / f"tts_{profile_id}_{ts}.wav"

    transcript_mode = bool(settings.get("use_transcript") and rec.transcript)
    if settings.get("use_transcript") and not rec.transcript:
        settings = {
            **settings,
            "use_transcript": False,
            "transcript_warning": "no transcript on selected reference",
        }

    backend.synthesize(
        text=text,
        reference_audio=Path(rec.path),
        transcript=rec.transcript if transcript_mode else None,
        output_path=out,
        seed=seed,
        **{k: v for k, v in settings.items() if k not in {"use_transcript"}},
    )

    provenance = {
        "generated_by": "EchoTwin",
        "ai_generated_disclosure": "This audio was generated by an AI voice model "
        "conditioned on authorized reference recordings.",
        "backend": backend_name,
        "backend_version": caps.get("version", ""),
        "profile_id": profile_id,
        "reference_recording_ids": [chosen_id, *[i for i in ids if i != chosen_id]],
        "reference_language_match": chosen_id != ids[0],
        "created_at": datetime.now(UTC).isoformat(),
        "settings": {k: v for k, v in settings.items() if k != "use_transcript"},
        "seed": seed,
    }
    meta_path = Path(str(out) + ".provenance.json")
    import json

    meta_path.write_text(json.dumps(provenance, indent=2, ensure_ascii=False), encoding="utf-8")

    return SynthesisResult(
        output_path=str(out),
        backend=backend_name,
        backend_version=str(caps.get("version", "")),
        model_id=str(getattr(backend, "model_id", backend_name)),
        reference_recording_ids=[chosen_id, *[i for i in ids if i != chosen_id]],
        language=language,
        transcript_mode=transcript_mode,
        settings={k: v for k, v in settings.items() if k != "use_transcript"},
        seed=seed,
        provenance=provenance,
    )
